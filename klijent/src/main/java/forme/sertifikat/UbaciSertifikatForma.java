    private void jButtonUbaciActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonUbaciActionPerformed
        try {
            String naziv = jTextFieldNaziv.getText().trim();
            String institucija = jTextFieldInstitucija.getText().trim();

            validiraj(naziv, institucija);

            Sertifikat sertifikat = new Sertifikat(null, institucija, naziv);
            ClientController.getInstance().ubaciSertifikat(sertifikat);
            JOptionPane.showMessageDialog(this, "Sistem je zapamtio sertifikat!", "Uspeh!", JOptionPane.INFORMATION_MESSAGE);
            this.dispose();
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "Sistem ne moze da zapamti sertifikat!", "Greska!", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jButtonUbaciActionPerformed

