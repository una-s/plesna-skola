    private void validiraj(String naziv, String institucija) throws Exception {
        String error = "";

        if (naziv.isEmpty()) {
            error += "Naziv sertifikata ne moze biti prazan!\n";
        }
        if (institucija.isEmpty()) {
            error += "Institucija ne moze biti prazna!\n";
        }

        if (!error.isEmpty()) {
            throw new Exception(error);
        }
    }
