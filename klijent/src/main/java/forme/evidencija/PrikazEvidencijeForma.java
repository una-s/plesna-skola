    private void jButtonDetaljiEvidencijeActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonDetaljiEvidencijeActionPerformed
        int selektovaniRed = jTableEvidencija.getSelectedRow();
        if (selektovaniRed == -1) {
            JOptionPane.showMessageDialog(this, "Evidencija casova nije odabrana!", "Greska!", JOptionPane.ERROR_MESSAGE);
            return;
        }
        ModelTabeleEvidencijaCasova mte = (ModelTabeleEvidencijaCasova) jTableEvidencija.getModel();
        EvidencijaCasova e = mte.getEvidencije().get(selektovaniRed);
        try {
            EvidencijaCasova evidencija = ClientController.getInstance().vratiEvidencijaCasova(e);
            JOptionPane.showMessageDialog(this, "Sistem je nasao evidenciju casova!", "Uspeh!", JOptionPane.INFORMATION_MESSAGE);
            DetaljiEvidencijeForma def = new DetaljiEvidencijeForma(evidencija);
            def.setVisible(true);
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage(), "Greska!", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jButtonDetaljiEvidencijeActionPerformed

    private void jButtonPromeniEvidencijuActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonPromeniEvidencijuActionPerformed
        int selektovaniRed = jTableEvidencija.getSelectedRow();
        if (selektovaniRed == -1) {
            JOptionPane.showMessageDialog(this, "Evidencija casova za promenu nije izabrana!", "Greska!", JOptionPane.ERROR_MESSAGE);
            return;
        }
        ModelTabeleEvidencijaCasova mte = (ModelTabeleEvidencijaCasova) jTableEvidencija.getModel();
        EvidencijaCasova e = mte.getEvidencije().get(selektovaniRed);
        try {
            EvidencijaCasova evidencija = ClientController.getInstance().vratiEvidencijaCasova(e);
            PromeniEvidencijuForma pef = new PromeniEvidencijuForma(this, evidencija);
            JOptionPane.showMessageDialog(this, "Sistem je pronasao evidenciju casova!", "Uspeh!", JOptionPane.INFORMATION_MESSAGE);
            pef.setVisible(true);
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage(), "Greska!", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jButtonPromeniEvidencijuActionPerformed

