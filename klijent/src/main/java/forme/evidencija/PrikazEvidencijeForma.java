    private void prepareView() {
        try {
            jComboBoxProfesor.removeAllItems();
            List<Profesor> profesori = ClientController.getInstance().vratiListuSviProfesor();
            for (Profesor p : profesori) {
                jComboBoxProfesor.addItem(p);
            }
            jComboBoxProfesor.setSelectedIndex(-1);

            jComboBoxUcenik.removeAllItems();
            List<Ucenik> ucenici = ClientController.getInstance().vratiListuSviUcenik();
            for (Ucenik u : ucenici) {
                jComboBoxUcenik.addItem(u);
            }
            jComboBoxUcenik.setSelectedIndex(-1);
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage(), "Greska!", JOptionPane.ERROR_MESSAGE);
        }
        popuniTabelu();
    }

    void popuniTabelu() {
        try {
            List<EvidencijaCasova> evidencije = ClientController.getInstance().vratiListuEvidencijaCasova();
            ModelTabeleEvidencijaCasova mte = new ModelTabeleEvidencijaCasova(evidencije);
            jTableEvidencija.setModel(mte);
        } catch (Exception ex) {
            ex.printStackTrace();
            JOptionPane.showMessageDialog(this, ex.getMessage(), "Greska!", JOptionPane.ERROR_MESSAGE);
        }
    }
