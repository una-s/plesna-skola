    private void jButtonSacuvajActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonSacuvajActionPerformed
        try {
            Profesor profesor = (Profesor) jComboBoxProfesor.getSelectedItem();
            Ucenik ucenik = (Ucenik) jComboBoxUcenik.getSelectedItem();
            String skolskaGodina = jTextFieldSkolskaGodina.getText().trim();
            String datumPocetkaStr = jTextFieldDatumPocetka.getText().trim();
            String datumZavrsetkaStr = jTextFieldDatumZavrsetka.getText().trim();

            validirajEvidenciju(profesor, ucenik, skolskaGodina, datumPocetkaStr, datumZavrsetkaStr);

            SimpleDateFormat sdf = new SimpleDateFormat("dd.MM.yyyy");
            Date datumPocetka = sdf.parse(datumPocetkaStr);
            Date datumZavrsetka = sdf.parse(datumZavrsetkaStr);

            if (ec == null) {
                EvidencijaCasova evidencija = new EvidencijaCasova();
                evidencija.setProfesor(profesor);
                evidencija.setUcenik(ucenik);
                evidencija.setSkolskaGodina(skolskaGodina);
                evidencija.setDatumPocetka(datumPocetka);
                evidencija.setDatumZavrsetka(datumZavrsetka);
                evidencija.setStavke(stavkeEvidencije);
                ClientController.getInstance().ubaciEvidencijaCasova(evidencija);
                JOptionPane.showMessageDialog(this, "Sistem je zapamtio evidenciju casova!", "Uspeh!", JOptionPane.INFORMATION_MESSAGE);
            } else {
                ec.setProfesor(profesor);
                ec.setUcenik(ucenik);
                ec.setSkolskaGodina(skolskaGodina);
                ec.setDatumPocetka(datumPocetka);
                ec.setDatumZavrsetka(datumZavrsetka);
                ec.setStavke(stavkeEvidencije);
                ClientController.getInstance().promeniEvidencijaCasova(ec);
                JOptionPane.showMessageDialog(this, "Sistem je zapamtio evidenciju casova!", "Uspeh!", JOptionPane.INFORMATION_MESSAGE);
            }

            pef.popuniTabelu();
            this.dispose();
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "Sistem ne moze da zapamti evidenciju casova!", "Greska!", JOptionPane.ERROR_MESSAGE);
        }

    }//GEN-LAST:event_jButtonSacuvajActionPerformed

    private void jButtonDodajStavkuActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonDodajStavkuActionPerformed
        Cas cas = (Cas) jComboBoxCasovi.getSelectedItem();
        String ocenaStr = jTextFieldOcena.getText().trim();
        String napomena = jTextFieldNapomena.getText().trim();
        String datumStr = jTextFieldDatumPrisustva.getText().trim();

        try {
            validirajStavku(cas, ocenaStr, datumStr);
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage(), "Greska!", JOptionPane.ERROR_MESSAGE);
            return;
        }

        try {
            SimpleDateFormat sdf = new SimpleDateFormat("dd.MM.yyyy");
            Date datumPrisustva = sdf.parse(datumStr);
            int ocena = Integer.parseInt(ocenaStr);

            StavkaEvidencijeCasova nova = new StavkaEvidencijeCasova();
            nova.setRb((long) stavkeEvidencije.size() + 1);
            nova.setCas(cas);
            nova.setOcena(ocena);
            nova.setDatumPrisustva(datumPrisustva);
            nova.setNapomena(napomena);

            stavkeEvidencije.add(nova);
            popuniTabeluStavki();

            jComboBoxCasovi.setSelectedIndex(-1);
            jTextFieldOcena.setText("");
            jTextFieldNapomena.setText("");
            jTextFieldDatumPrisustva.setText("dd.MM.yyyy");
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "Sistem ne moze da doda stavku!", "Greska!", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jButtonDodajStavkuActionPerformed

