    private void prepareView() {
        try {
            // profesor je uvek ulogovani - ne moze da se menja
            jComboBoxProfesor.removeAllItems();
            jComboBoxProfesor.addItem(ClientController.getInstance().getUlogovani());
            jComboBoxProfesor.setSelectedItem(ClientController.getInstance().getUlogovani());
            jComboBoxProfesor.setEnabled(false);

            jComboBoxUcenik.removeAllItems();
            List<Ucenik> ucenici = ClientController.getInstance().vratiListuSviUcenik();
            for (Ucenik u : ucenici) {
                jComboBoxUcenik.addItem(u);
            }
            jComboBoxUcenik.setSelectedIndex(-1);

            jComboBoxCasovi.removeAllItems();
            List<Cas> casovi = ClientController.getInstance().vratiListuSviCas();
            for (Cas c : casovi) {
                jComboBoxCasovi.addItem(c);
            }
            jComboBoxCasovi.setSelectedIndex(-1);

            // calculated polja - non-editable
            jTextFieldBrojPrisustva.setEnabled(false);
            jTextFieldTrajanjeEvidencije.setEnabled(false);
            jTextFieldProsecnaOcena.setEnabled(false);

            popuniTabeluStavki();
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage(), "Greska!", JOptionPane.ERROR_MESSAGE);
        }
    }

    private void popuniPolja() {
        SimpleDateFormat sdf = new SimpleDateFormat("dd.MM.yyyy");

        jComboBoxProfesor.setSelectedItem(ec.getProfesor());
        jComboBoxUcenik.setSelectedItem(ec.getUcenik());
        jTextFieldSkolskaGodina.setText(ec.getSkolskaGodina());
        jTextFieldDatumPocetka.setText(sdf.format(ec.getDatumPocetka()));
        jTextFieldDatumZavrsetka.setText(sdf.format(ec.getDatumZavrsetka()));

        popuniTabeluStavki();
    }

    private void popuniTabeluStavki() {
        ModelTabeleStavkaEvidencijeCasova mtsec = new ModelTabeleStavkaEvidencijeCasova(stavkeEvidencije);
        jTableStavkeEvidencije.setModel(mtsec);
        osvežiKalkulisanaPolja();
    }

    private void osvežiKalkulisanaPolja() {
        jTextFieldBrojPrisustva.setText(String.valueOf(stavkeEvidencije.size()));

        if (!stavkeEvidencije.isEmpty()) {
            double prosek = stavkeEvidencije.stream()
                    .mapToInt(StavkaEvidencijeCasova::getOcena)
                    .average()
                    .orElse(0.0);
            jTextFieldProsecnaOcena.setText(String.format("%.2f", prosek));
        } else {
            jTextFieldProsecnaOcena.setText("0.0");
        }

        try {
            SimpleDateFormat sdf = new SimpleDateFormat("dd.MM.yyyy");
            if (!jTextFieldDatumPocetka.getText().isEmpty() && !jTextFieldDatumZavrsetka.getText().isEmpty()) {
                Date poc = sdf.parse(jTextFieldDatumPocetka.getText());
                Date kraj = sdf.parse(jTextFieldDatumZavrsetka.getText());
                long trajanje = (kraj.getTime() - poc.getTime()) / (1000 * 60 * 60 * 24);
                jTextFieldTrajanjeEvidencije.setText(String.valueOf(trajanje));
            }
        } catch (Exception e) {
            jTextFieldTrajanjeEvidencije.setText("0");
        }
    }

    private void validirajStavku(Cas cas, String ocenaStr, String datumStr) throws Exception {
        String error = "";

        if (cas == null) {
            error += "Cas mora biti izabran!\n";
        }
        if (ocenaStr.isEmpty()) {
            error += "Ocena ne sme biti prazna!\n";
        } else {
            try {
                int ocena = Integer.parseInt(ocenaStr);
                if (ocena < 1 || ocena > 5) {
                    error += "Ocena mora biti izmedju 1 i 5!\n";
                }
            } catch (NumberFormatException e) {
                error += "Ocena mora biti ceo broj!\n";
            }
        }
        if (datumStr.isEmpty() || datumStr.equals("dd.MM.yyyy")) {
            error += "Datum prisustva ne sme biti prazan!\n";
        } else {
            try {
                SimpleDateFormat sdf = new SimpleDateFormat("dd.MM.yyyy");
                Date datumPrisustva = sdf.parse(datumStr);

                String pocStr = jTextFieldDatumPocetka.getText().trim();
                String krajStr = jTextFieldDatumZavrsetka.getText().trim();

                if (!pocStr.isEmpty() && !krajStr.isEmpty()
                        && !pocStr.equals("dd.MM.yyyy") && !krajStr.equals("dd.MM.yyyy")) {
                    Date poc = sdf.parse(pocStr);
                    Date kraj = sdf.parse(krajStr);

                    if (datumPrisustva.before(poc) || datumPrisustva.after(kraj)) {
                        error += "Datum prisustva mora biti izmedju datuma pocetka i zavrsetka evidencije!\n";
                    }
                }
            } catch (Exception e) {
                error += "Datum prisustva nije ispravnog formata! Koristite dd.MM.yyyy\n";
            }
        }

        if (!error.isEmpty()) {
            throw new Exception(error);
        }
    }

    private void validirajEvidenciju(Profesor profesor, Ucenik ucenik, String skolskaGodina,
            String datumPocetkaStr, String datumZavrsetkaStr) throws Exception {
        String error = "";

        if (profesor == null) {
            error += "Profesor mora biti izabran!\n";
        }
        if (ucenik == null) {
            error += "Ucenik mora biti izabran!\n";
        }
        if (skolskaGodina.isEmpty()) {
            error += "Skolska godina ne sme biti prazna!\n";
        } else if (!skolskaGodina.matches(".*/.+")) {
            error += "Skolska godina mora biti u formatu 'xxxx/xxxx'!\n";
        }
        if (datumPocetkaStr.isEmpty()) {
            error += "Datum pocetka ne sme biti prazan!\n";
        }
        if (datumZavrsetkaStr.isEmpty()) {
            error += "Datum zavrsetka ne sme biti prazan!\n";
        }
        if (stavkeEvidencije.isEmpty()) {
            error += "Evidencija mora imati bar jednu stavku!\n";
        }

        if (!error.isEmpty()) {
            throw new Exception(error);
        }

        // provera datuma i skolske godine
        try {
            SimpleDateFormat sdf = new SimpleDateFormat("dd.MM.yyyy");
            Date poc = sdf.parse(datumPocetkaStr);
            Date kraj = sdf.parse(datumZavrsetkaStr);

            if (kraj.before(poc)) {
                throw new Exception("Datum zavrsetka mora biti nakon datuma pocetka!\n");
            }

            if (skolskaGodina.matches("\\d{4}/\\d{4}")) {
                int godinaOd = Integer.parseInt(skolskaGodina.split("/")[0]);
                int godinaDo = Integer.parseInt(skolskaGodina.split("/")[1]);

                Calendar cal = Calendar.getInstance();

                cal.setTime(poc);
                if (cal.get(Calendar.YEAR) != godinaOd) {
                    throw new Exception("Godina datuma pocetka mora biti jednaka prvoj godini skolske godine!\n");
                }

                cal.setTime(kraj);
                if (cal.get(Calendar.YEAR) != godinaDo) {
                    throw new Exception("Godina datuma zavrsetka mora biti jednaka drugoj godini skolske godine!\n");
                }
            }
        } catch (java.text.ParseException e) {
            throw new Exception("Datum nije ispravnog formata! Koristite dd.MM.yyyy\n");
        }
    }

