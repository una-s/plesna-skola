    private void jButtonDogadjajActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonDogadjajActionPerformed
        try {
            if (mf == ModForme.OBRISI) {
                ClientController.getInstance().obrisiUcenik(u);
                JOptionPane.showMessageDialog(this, "Sistem je obrisao ucenika!", "Uspeh!", JOptionPane.INFORMATION_MESSAGE);
                puf.prepareView();
                this.dispose();
                return;
            }

            String ime = jTextFieldIme.getText().trim();
            String prezime = jTextFieldPrezime.getText().trim();
            String brojTelefona = jTextFieldTelefon.getText().trim();
            PlesniNivo pn = (PlesniNivo) jComboBoxPlesniNivo.getSelectedItem();

            validiraj(ime, prezime, brojTelefona, pn);

            if (mf == ModForme.DODAJ) {
                Ucenik ucenik = new Ucenik(null, ime, prezime, brojTelefona, pn);
                ClientController.getInstance().ubaciUcenik(ucenik);
                JOptionPane.showMessageDialog(this, "Sistem je zapamtio ucenika!", "Uspeh!", JOptionPane.INFORMATION_MESSAGE);
            } else if (mf == ModForme.IZMENI) {
                u.setIme(ime);
                u.setPrezime(prezime);
                u.setBrojTelefona(brojTelefona);
                u.setPlesniNivo(pn);
                ClientController.getInstance().promeniUcenik(u);
                JOptionPane.showMessageDialog(this, "Sistem je zapamtio ucenika!", "Uspeh!", JOptionPane.INFORMATION_MESSAGE);
            }

            puf.prepareView();
            this.dispose();
        } catch (Exception ex) {
            if (mf == ModForme.OBRISI) {
                JOptionPane.showMessageDialog(this, "Sistem ne moze da obrise ucenika!", "Greska!", JOptionPane.ERROR_MESSAGE);
            } else {
                JOptionPane.showMessageDialog(this, "Sistem ne moze da zapamti ucenika!", "Greska!", JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_jButtonDogadjajActionPerformed


