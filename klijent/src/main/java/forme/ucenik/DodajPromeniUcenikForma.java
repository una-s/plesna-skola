    private void prepareView() {
        try {
            jComboBoxPlesniNivo.removeAllItems();
            List<PlesniNivo> plesniNivoi = ClientController.getInstance().vratiListuPlesniNivo();
            for (PlesniNivo pn : plesniNivoi) {
                jComboBoxPlesniNivo.addItem(pn);
            }
            jComboBoxPlesniNivo.setSelectedIndex(-1);
        } catch (Exception ex) {
            ex.printStackTrace();
            JOptionPane.showMessageDialog(this, ex.getMessage(), "Greska!", JOptionPane.ERROR_MESSAGE);
        }

        podesiMod();
    }

    private void validiraj(String ime, String prezime, String brojTelefona, PlesniNivo pn) throws Exception {
        String error = "";

        if (ime.isEmpty()) {
            error += "Polje ime ne moze biti prazno!\n";
        }
        if (prezime.isEmpty()) {
            error += "Polje prezime ne moze biti prazno!\n";
        }
        if (brojTelefona.isEmpty()) {
            error += "Polje broj telefona ne moze biti prazno!\n";
        }
        if (pn == null) {
            error += "Morate izabrati plesni nivo!\n";
        }

        if (!error.isEmpty()) {
            throw new Exception(error);
        }
    }

    private void popuniUcenika() {
        jTextFieldIme.setText(u.getIme());
        jTextFieldPrezime.setText(u.getPrezime());
        jTextFieldTelefon.setText(u.getBrojTelefona());
        jComboBoxPlesniNivo.setSelectedItem(u.getPlesniNivo());
    }

    private void podesiMod() {
        if (mf == ModForme.DODAJ) {
            this.setTitle("Dodavanje ucenika");
        } else if (mf == ModForme.IZMENI) {
            popuniUcenika();
            this.setTitle("Promena ucenika");
        } else if (mf == ModForme.OBRISI) {
            popuniUcenika();
            jTextFieldIme.setEditable(false);
            jTextFieldPrezime.setEditable(false);
            jTextFieldTelefon.setEditable(false);
            jComboBoxPlesniNivo.setEnabled(false);
            jButtonDogadjaj.setText("Obrisi");
            this.setTitle("Brisanje ucenika");
        } else if (mf == ModForme.DETALJAN_PRIKAZ) {
            popuniUcenika();
            jTextFieldIme.setEditable(false);
            jTextFieldPrezime.setEditable(false);
            jTextFieldTelefon.setEditable(false);
            jComboBoxPlesniNivo.setEnabled(false);
            jButtonDogadjaj.setVisible(false);
            jButtonOdustani.setText("Nazad");
            this.setTitle("Prikaz ucenika");
        }
    }
